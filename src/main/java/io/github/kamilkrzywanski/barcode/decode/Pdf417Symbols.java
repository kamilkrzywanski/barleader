    /** Bar widths of every symbol, built the same way as {@code MakeBarSizeTable}. Index 0 is the left bar. */
    private static final byte[][] BAR_SIZE = new byte[COUNT][8];
    private static final int[] SUM_OF_SQUARES = new int[COUNT];

    static {
        if (SYMBOLS.length != COUNT || CODEWORDS.length != COUNT) {
            throw new ExceptionInInitializerError("PDF417 symbol table");
        }
        for (int i = 1; i < SYMBOLS.length; i++) {
            if (SYMBOLS[i] <= SYMBOLS[i - 1]) {
                throw new ExceptionInInitializerError("PDF417 symbol order");
            }
        }
        for (int i = 0; i < COUNT; i++) {
            int symbol = SYMBOLS[i] | 0x10000;
            int bit = symbol & 1;
            int total = 0;
            for (int bar = 0; bar < 8; bar++) {
                int size = 0;
                while ((symbol & 1) == bit) {
                    size++;
                    symbol >>>= 1;
                    if (size > 17) {
                        throw new ExceptionInInitializerError("PDF417 bar width");
                    }
                }
                bit = symbol & 1;
                BAR_SIZE[i][7 - bar] = (byte) size;
                SUM_OF_SQUARES[i] += size * size;
                total += size;
            }
            if (total != 17) {
                throw new ExceptionInInitializerError("PDF417 symbol width");
            }
        }
    }

    private Pdf417Symbols() {
    }

    /** {@code GetCodeword(int)}. A symbol that is not in the table returns -1. */
    static int codeword(int symbol) {
        if ((symbol & 0xFFFF0000) != 0x10000) {
            return -1;
        }
        int index = Arrays.binarySearch(SYMBOLS, symbol & 0xFFFF);
        if (index < 0) {
            return -1;
        }
        return Math.floorMod(CODEWORDS[index] - 1, MODULUS);
    }

    /**
     * {@code GetDecodedValue}. Samples the eight measured bars onto 17 modules and, when that
     * symbol is not in the table, picks the symbol with the closest bar-width ratios.
     */
    static int decodedValue(int[] moduleBitCount) {
        int sampled = bitValue(sample(moduleBitCount));
        if (codeword(sampled) != -1) {
            return sampled;
        }
        int sum = 0;
        for (int count : moduleBitCount) {
            sum += count;
        }
        int bestScore = Integer.MAX_VALUE;
        int best = -1;
        for (int j = 0; j < COUNT; j++) {
            int dot = 0;
            for (int bar = 0; bar < 8; bar++) {
                dot += BAR_SIZE[j][bar] * moduleBitCount[bar];
            }
            int score = sum * SUM_OF_SQUARES[j] - 34 * dot;
            if (score < bestScore) {
                bestScore = score;
                best = SYMBOLS[j] | 0x10000;
            }
        }
        return best;
    }

    /** {@code GetCodewordBucketNumber}. The symbol is the 17-bit pattern, not the codeword index. */
    static int bucket(int symbol) {
        int[] bars = new int[8];
        int previous = 0;
        int bar = bars.length - 1;
        while (true) {
            if ((symbol & 1) != previous) {
                previous = symbol & 1;
                bar--;
                if (bar < 0) {
                    break;
                }
            }
            bars[bar]++;
            symbol >>= 1;
        }
        return (bars[0] - bars[2] + bars[4] - bars[6] + 9) % 9;
    }

    /** {@code SampleBitCounts}. */
    private static int[] sample(int[] moduleBitCount) {
        float sum = 0f;
        for (int count : moduleBitCount) {
            sum += count;
        }
        int[] result = new int[8];
        int index = 0;
        int previous = 0;
        for (int module = 0; module < 17; module++) {
            float at = sum / 34f + (module * sum) / 17f;
            if (previous + moduleBitCount[index] <= at) {
                previous += moduleBitCount[index];
                index++;
                if (index == moduleBitCount.length) {
                    break;
                }
            }
            result[index]++;
        }
        return result;
    }

    /** {@code GetBitValue}. Even bars are black. */
    private static int bitValue(int[] moduleBitCount) {
        int result = 0;
        for (int bar = 0; bar < moduleBitCount.length; bar++) {
            int bit = bar % 2 == 0 ? 1 : 0;
            for (int i = 0; i < moduleBitCount[bar]; i++) {
                result = (result << 1) | bit;
            }
        }
        return result;
    }
